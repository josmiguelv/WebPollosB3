import assert from 'node:assert/strict';
import fs from 'node:fs';
const vite = fs.readFileSync('vite.config.ts', 'utf8');
const example = fs.readFileSync('.env.example', 'utf8');
const helper = fs.readFileSync('client/src/lib/storefront/api-base.ts', 'utf8');
const mobile = fs.readFileSync('client/src/lib/storefront/mobile-config.ts', 'utf8');
const transport = fs.readFileSync('client/src/lib/storefront/web-order-transport.ts', 'utf8');
const ignore = fs.readFileSync('.gitignore', 'utf8');
assert.ok(example.includes('VITE_B3_API_BASE_URL=https://'), 'Una URL principal, lista para copiar al .env');
assert.ok(vite.includes("envDir: envRoot"), 'Vite lee el .env de la raíz');
assert.ok(vite.includes("loadEnv(mode, envRoot, 'VITE_B3_')"), 'Proxy lee la misma ubicación que el cliente');
assert.ok(vite.includes('env.VITE_B3_API_BASE_URL'), 'Proxy utiliza URL única');
assert.ok(mobile.includes("getB3MobileApiBase() + '/config'"), 'Configuración usa URL única');
assert.ok(transport.includes('getB3MobileApiBase()'), 'Pedidos usan URL única');
assert.ok(helper.includes('import.meta.env.VITE_B3_API_BASE_URL'), 'Cliente utiliza URL única');
assert.ok(helper.includes("'/api/v1/mobile'"), 'Mantiene rutas oficiales del contrato');
assert.ok(vite.includes("'/b3-mobile-images'") && vite.includes("'/b3-mobile-api'"), 'Imágenes y pedidos usan el proxy');
assert.ok(ignore.split(/\r?\n/).includes('.env'), 'Nunca agregar credenciales de .env a Git');
assert.ok(!example.includes('VITE_B3_MOBILE_CONFIG_URL='), 'La plantilla no tiene dos variables para el mismo origen');
console.log('PASS: una sola URL de API desde el .env de la raíz, sin cambiar Carta.');
